"""Audit the 260 unparsed Jinshi rank strings and the 武舉 rows.

Aggregate output only: no names, PersonIDs or coordinates. The goal is to bound
the elite (1甲/2甲) count rather than assume that every unparsed row is elite.

Usage:
    set MING_JINSHI_RAW=I:\\L\\Work_ming\\raw\\明进士.xlsx
    python scripts/analyze_unparsed_ranks.py
"""

from __future__ import annotations

import os
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = Path(os.environ.get("MING_JINSHI_RAW", ROOT / "raw" / "明进士.xlsx"))
OUT_CSV = Path(os.environ.get("MING_UNPARSED_OUT", ROOT / "data" / "derived" / "jinshi_unparsed_summary.csv"))
OUT_MD = Path(os.environ.get("MING_UNPARSED_MD", ROOT / "docs" / "jinshi_unparsed_audit.md"))

import sys

sys.path.insert(0, str(ROOT))
from src.data_processing.jinshi_rank import rank_class  # noqa: E402

WINDOW = (1521, 1619)
WUJU = "武舉"


def main() -> None:
    if not RAW.exists():
        raise SystemExit(f"raw export not found: {RAW}")

    df = pd.read_excel(RAW)
    df["year"] = pd.to_numeric(df.get("EntryYear"), errors="coerce")
    df["rank_class"] = df.get("EntryRank").map(rank_class)
    df["is_wuju"] = df.get("EntryChn").astype(str).str.contains(WUJU, na=False)
    win = df[df["year"].between(*WINDOW)].copy()

    strict = win[win["rank_class"].isin([1, 2])]
    strict_civil = strict[~strict["is_wuju"]]
    unparsed = win[win["rank_class"].isna()]
    civil_unparsed = unparsed[~unparsed["is_wuju"]]

    missing = unparsed[unparsed["EntryRank"].isna()]
    zero = unparsed[unparsed["EntryRank"].astype(str) == "0"]
    top3 = unparsed[unparsed["EntryRank"].astype(str).isin(["第1名", "第2名", "第3名"])]
    prose_erjia = unparsed[unparsed["EntryRank"].astype(str).str.contains("二甲", na=False)]

    wuju_all = df[df["is_wuju"]]
    wuju_win = win[win["is_wuju"]]
    wuju_elite_win = wuju_win[wuju_win["rank_class"].isin([1, 2])]
    wuju_elite_out = wuju_all[(~wuju_all["year"].between(*WINDOW)) & wuju_all["rank_class"].isin([1, 2])]

    confirmed = len(strict_civil) + len(prose_erjia[~prose_erjia["is_wuju"]])
    civil_top3 = top3[~top3["is_wuju"]]
    probable = confirmed + len(civil_top3)
    upper = len(strict_civil) + len(civil_unparsed)

    metrics = [
        ("raw_rows", len(df)),
        ("window_rows", len(win)),
        ("strict_elite", len(strict)),
        ("strict_elite_civil", len(strict_civil)),
        ("strict_elite_civil_with_coords", int(strict_civil[["X", "Y"]].notna().all(axis=1).sum())),
        ("unparsed_total", len(unparsed)),
        ("unparsed_missing_rank", len(missing)),
        ("unparsed_malformed", len(unparsed) - len(missing)),
        ("unparsed_zero", len(zero)),
        ("unparsed_top3_names", len(top3)),
        ("unparsed_prose_erjia", len(prose_erjia)),
        ("civil_unparsed_total", len(civil_unparsed)),
        ("wuju_total", len(wuju_all)),
        ("wuju_window", len(wuju_win)),
        ("wuju_elite_window", len(wuju_elite_win)),
        ("wuju_elite_outside_window", len(wuju_elite_out)),
        ("elite_confirmed_lower", confirmed),
        ("elite_probable_lower", probable),
        ("elite_upper_civil", upper),
    ]

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(metrics, columns=["metric", "value"]).to_csv(
        OUT_CSV, index=False, encoding="utf-8-sig"
    )

    lines = [
        "# Jinshi unparsed-rank audit",
        "",
        "Generated by `scripts/analyze_unparsed_ranks.py`. Aggregate counts only.",
        "",
        "The old regex treated every unparsed rank as unknown. This audit separates",
        "missing ranks from malformed strings and checks whether any 武舉 record",
        "enters the 1甲/2甲 layer.",
        "",
        "## 1. Unparsed rows",
        "",
        "| Group | Rows | With coordinates |",
        "|---|---:|---:|",
    ]
    for name, frame in (
        ("Missing `EntryRank`", missing),
        ("`0` placeholder", zero),
        ("`第1/2/3名`", top3),
        ("Prose containing `二甲`", prose_erjia),
    ):
        lines.append(
            f"| {name} | {len(frame)} | {int(frame[['X', 'Y']].notna().all(axis=1).sum())} |"
        )
    lines += [
        "",
        f"Total unparsed: **{len(unparsed)}** ({len(missing)} missing + {len(unparsed) - len(missing)} malformed).",
        "",
        "Malformed strings are few:",
        "",
        "| String | Rows |",
        "|---|---:|",
    ]
    for value, count in unparsed["EntryRank"].dropna().astype(str).value_counts().items():
        lines.append(f"| `{value}` | {count} |")

    lines += [
        "",
        "## 2. 武舉",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| 武舉 rows, full export | {len(wuju_all)} |",
        f"| 武舉 rows in 1521–1619 | {len(wuju_win)} |",
        f"| 武舉 elite in window | {len(wuju_elite_win)} |",
        f"| 武舉 elite outside window | {len(wuju_elite_out)} |",
        "",
        "All 武舉 rows in the window are unparsed; one 2甲 武舉 sits in 1637,",
        "outside the analysis window. The 2,853 layer is therefore civil-only.",
        "",
        "## 3. Bounds on the civil elite",
        "",
        "| Definition | Rows |",
        "|---|---:|",
        f"| Strict regex, civil 1甲/2甲 | {len(strict_civil)} |",
        f"| + prose `二甲` (confirmed) | {confirmed} |",
        f"| + civil `第1/2/3名` (probable 1甲) | {probable} |",
        f"| Upper bound: all civil unparsed treated as elite | {upper} |",
        "",
        "Use **2,855** as the confirmed lower bound, 2,857 as the probable lower",
        "bound, and 3,104 as the civil-only upper bound. The published 2,841 is the",
        "strict-with-coordinates layer; adding the one prose `二甲` with coordinates",
        "gives 2,842.",
        "",
        "The difference is 1–3 records; the models are not re-run for this audit.",
    ]
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
