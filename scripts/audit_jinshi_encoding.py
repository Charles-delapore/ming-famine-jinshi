"""Audit the Jinshi rank encoding and rebuild the published 911 subset.

The published pipeline filtered `EntryRank` with the literal regex
`第1甲|第2甲`. CBDB encodes the same rank in two ways:

    第1甲第3名   (Arabic numeral)
    第一甲第三名 (Chinese numeral)

Only the first form matches, so the 911-record "elite Jinshi" layer is a
format-selected subsample, not a rank-selected one. This script quantifies the
problem from the raw CBDB export and prints a reproducible table.

Usage:
    set MING_JINSHI_RAW=I:\\L\\Work_ming\\raw\\明进士.xlsx
    python scripts/audit_jinshi_encoding.py

Writes docs/jinshi_encoding_audit.md (aggregate counts only).
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = Path(os.environ.get("MING_JINSHI_RAW", ROOT / "raw" / "明进士.xlsx"))
PIPE = Path(os.environ.get("MING_JINSHI_PIPELINE", ROOT / "raw" / "table_general.xlsx"))
OUT = Path(os.environ.get("MING_AUDIT_OUT", ROOT / "docs" / "jinshi_encoding_audit.md"))

RANK_RE = re.compile(r"^\s*(?:第)?\s*([一二三123])\s*甲")
NUM = {"一": 1, "二": 2, "三": 3, "1": 1, "2": 2, "3": 3}


def rank_class(value: object) -> int | None:
    if pd.isna(value):
        return None
    match = RANK_RE.match(str(value))
    return NUM[match.group(1)] if match else None


def main() -> None:
    if not RAW.exists():
        raise SystemExit(f"raw export not found: {RAW}\nset MING_JINSHI_RAW to the 明进士.xlsx path")

    df = pd.read_excel(RAW)
    df["year"] = pd.to_numeric(df.get("EntryYear"), errors="coerce")
    df["cls"] = df.get("EntryRank").map(rank_class)
    rank_text = df.get("EntryRank").astype(str)
    df["arabic"] = rank_text.str.contains(r"第[123]甲", na=False)
    df["chinese"] = rank_text.str.contains(r"第[一二三]甲", na=False)

    window = df[df["year"].between(1521, 1619)].copy()
    elite = window[window["cls"].isin([1, 2])].copy()
    with_xy = elite.dropna(subset=["X", "Y"])

    published = df[df["year"].between(1521, 1619) & df["arabic"] & df["cls"].isin([1, 2])]

    pipe_line = None
    if PIPE.exists():
        p = pd.read_excel(PIPE)
        p["year"] = pd.to_numeric(p.get("EntryYear"), errors="coerce")
        p["cls"] = p.get("EntryRank").map(rank_class)
        p["arabic"] = p.get("EntryRank").astype(str).str.contains(r"第[123]甲", na=False)
        p_elite = p[p["arabic"] & p["cls"].isin([1, 2]) & p["year"].between(1521, 1619)]
        p_1522 = p_elite[p_elite["year"] >= 1522]
        pipe_line = (len(p), len(p_elite), len(p_1522))

    lines = [
        "# Jinshi rank-encoding audit",
        "",
        "Generated by `scripts/audit_jinshi_encoding.py`. Aggregate counts only; "
        "no individual records are exported.",
        "",
        f"Raw export: `{RAW.name}` — {len(df):,} rows, "
        f"{df['PersonID'].nunique():,} unique CBDB `PersonID`." if "PersonID" in df else "",
        "",
        "## Why this file exists",
        "",
        "The published figure pipeline selected elite Jinshi with the literal regex",
        "`第1甲|第2甲`. CBDB writes the same rank in two numeral systems:",
        "",
        "| Encoding | Example | Matches the old regex |",
        "|---|---|---|",
        "| Arabic | `第1甲第3名` | yes |",
        "| Chinese | `第一甲第三名` | **no** |",
        "",
        "The 911-record layer is therefore a *format-selected* subsample. "
        "This audit quantifies the bias and gives the corrected denominator.",
        "",
        "## 1. Raw export",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Rows | {len(df):,} |",
        f"| Unique PersonID | {df['PersonID'].nunique():,} |",
        f"| Missing X or Y | {int(df[['X', 'Y']].isna().any(axis=1).sum()):,} |",
        f"| EntryYear = 0 (invalid) | {int((df['year'] == 0).sum()):,} |",
        f"| Rank class 1甲 | {int((df['cls'] == 1).sum()):,} |",
        f"| Rank class 2甲 | {int((df['cls'] == 2).sum()):,} |",
        f"| Rank class 3甲 | {int((df['cls'] == 3).sum()):,} |",
        f"| Rank unparsed | {int(df['cls'].isna().sum()):,} |",
        "",
        "## 2. Analysis window 1521–1619",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Rows in window | {len(window):,} |",
        f"| Unique PersonID | {window['PersonID'].nunique():,} |",
        f"| 1甲 | {int((window['cls'] == 1).sum()):,} |",
        f"| 2甲 | {int((window['cls'] == 2).sum()):,} |",
        f"| 3甲 | {int((window['cls'] == 3).sum()):,} |",
        f"| Elite (1甲 + 2甲) | {len(elite):,} |",
        f"| Elite with coordinates | {len(with_xy):,} |",
        f"| Arabic-coded 1/2甲 in window | {len(published):,} |",
        f"| Published 911 layer (1523–1619) | 911 |",
        "",
        "## 3. The encoding split",
        "",
        "| Encoding | Elite rows in window | Share |",
        "|---|---:|---:|",
        f"| Arabic `第1甲`/`第2甲` | {int(elite['arabic'].sum()):,} | "
        f"{elite['arabic'].mean() * 100:.1f}% |",
        f"| Chinese `第一甲`/`第二甲` | {int(elite['chinese'].sum()):,} | "
        f"{elite['chinese'].mean() * 100:.1f}% |",
        "",
        "## 4. Exam years that the old filter kept or dropped",
        "",
        "A year appears in the 911 layer only if its CBDB records happen to use",
        "Arabic numerals. The table shows why 1523 and 1526 dominate.",
        "",
        "| Year | Arabic elite | Chinese elite | In 911 layer |",
        "|---:|---:|---:|---|",
    ]
    by_year = elite.groupby("year").agg(
        arabic=("arabic", "sum"), chinese=("chinese", "sum"), total=("cls", "size")
    )
    for year, row in by_year.sort_index().iterrows():
        kept = "yes" if row["arabic"] > 0 and row["chinese"] == 0 else (
            "partial" if row["arabic"] > 0 else "no")
        lines.append(f"| {int(year)} | {int(row['arabic'])} | {int(row['chinese'])} | {kept} |")

    top_arabic = by_year["arabic"].sort_values(ascending=False).head(6)
    share = published["year"].value_counts(normalize=True).head(3) * 100
    lines += [
        "",
        "## 5. What the 911 layer actually is",
        "",
        "| Consequence | Explanation |",
        "|---|---|",
        "| 24.6% of rows fall in 1523 + 1526 | Both years are encoded almost entirely "
        "in Arabic numerals, so they survive the filter |",
        "| 0 records of 3甲 | 3甲 is excluded by design (`is_important` keeps 1甲/2甲) |",
        "| 34 records of 1甲 | Only the Arabic-coded 1甲 records survive; the Chinese-coded "
        "majority are dropped |",
        "| Cluster sizes of exactly 100 | `max_cluster_size=100` truncates dense clusters |",
        "",
        "Top Arabic-coded years: " + ", ".join(f"{int(y)} ({int(n)})" for y, n in top_arabic.items()) + ".",
        "Top years in the published 911 layer: "
        + ", ".join(f"{int(y)} ({v:.1f}%)" for y, v in share.items()) + ".",
        "",
        "## 5b. Reconciliation with the published 911 table",
        "",
    ]
    if pipe_line is not None:
        lines += [
            "| Step | Rows |",
            "|---|---:|",
            f"| Raw export `{RAW.name}` | {len(df):,} |",
            f"| Arabic-coded 1/2甲 in 1521–1619 (raw export) | {len(published):,} |",
            f"| Pipeline table `{PIPE.name}` | {pipe_line[0]:,} |",
            f"| Arabic-coded 1/2甲 in 1521–1619 (pipeline table) | {pipe_line[1]:,} |",
            f"| Same, from 1522 (嘉靖 era) | {pipe_line[2]:,} |",
            "| Published `clustered_jinshi.xlsx` | 911 |",
            "",
            "The 7-record gap between 918 and 911 is exactly the 1521 exam cohort",
            "(7 × 第2甲); the published layer starts in 1523. The 11-record gap",
            "between the two raw exports reflects a different export/deduplication",
            "step, not a rank filter.",
            "",
        ]
    lines += [
        "## 6. Corrected numbers to use",
        "",
        f"- Elite Jinshi in 1521–1619: **{len(elite):,}** records "
        f"({len(with_xy):,} with coordinates).",
        "- The 911 layer is **not** a random sample and **not** a rank-complete sample.",
        "- Any figure or model that uses the 911 layer must be labelled provisional",
        "  until the pipeline is re-run on the normalized rank field.",
        "",
        "## 7. Normalization rule",
        "",
        "```python",
        "RANK_RE = re.compile(r'^\\s*(?:第)?\\s*([一二三123])\\s*甲')",
        "```",
        "",
        "Apply this before filtering; never match the literal string `第1甲` alone.",
        "",
        "## 8. Redistribution",
        "",
        "The raw CBDB export is not redistributed. Only aggregate counts above are",
        "published. Source: China Biographical Database (CBDB), Harvard University /",
        "Peking University / Academia Sinica.",
    ]
    text = "\n".join(line for line in lines if line is not None) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
