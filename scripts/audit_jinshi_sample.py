import os
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path(os.environ.get("MING_OUTPUT", ROOT / "output"))
OUT_MD = Path(os.environ.get("MING_AUDIT_OUT", ROOT / "docs" / "jinshi_sample_audit.md"))

j = pd.read_excel(OUTPUT / "clustered_jinshi.xlsx")
year_counts = j.groupby("EntryYear").size().sort_values(ascending=False)
share_1523_1526 = (year_counts.get(1523, 0) + year_counts.get(1526, 0)) / len(j) * 100
rank_prefix = j["EntryRank"].astype(str).str[:3].value_counts()
top_places = j["AddrChn"].value_counts().head(12)
xy = j["xy_count"].describe()

lines = [
    "# Jinshi sample audit (aggregate only)",
    "",
    "Generated by `scripts/audit_jinshi_sample.py` from the local result table. "
    "Only aggregate counts and place names are reported; no individual records are exported.",
    "",
    "| Metric | Value |",
    "|---|---:|",
    f"| Records | {len(j)} |",
    f"| Year range | {int(j.EntryYear.min())}–{int(j.EntryYear.max())} |",
    f"| Unique names | {j.NameChn.nunique()} |",
    f"| Duplicate-name rows | {len(j) - j.NameChn.nunique()} |",
    f"| Missing coordinates | {int(j[['X', 'Y']].isna().any(axis=1).sum())} |",
    f"| 1523 + 1526 records | {int(year_counts.get(1523, 0) + year_counts.get(1526, 0))} ({share_1523_1526:.1f}%) |",
    f"| Rank 第1甲 | {int(rank_prefix.get('第1甲', 0))} |",
    f"| Rank 第2甲 | {int(rank_prefix.get('第2甲', 0))} |",
    f"| Rank 第3甲 | {int(rank_prefix.get('第3甲', 0))} |",
    "",
    "## Top exam years",
    "",
    "| Year | Records |",
    "|---:|---:|",
]
for year, n in year_counts.head(12).items():
    lines.append(f"| {int(year)} | {int(n)} |")

lines += [
    "",
    "## Top places (AddrChn)",
    "",
    "| Place | Records |",
    "|---|---:|",
]
for place, n in top_places.items():
    lines.append(f"| {place} | {int(n)} |")

lines += [
    "",
    "## xy_count distribution",
    "",
    "| Stat | Value |",
    "|---|---:|",
]
for key in ["count", "mean", "std", "min", "25%", "50%", "75%", "max"]:
    lines.append(f"| {key} | {xy[key]:.2f} |")

lines += [
    "",
    "## What this audit does not establish",
    "",
    "- Whether the 911 records are a complete or representative sample of Ming Jinshi.",
    "- The upstream source and version (CBDB Ming dengke lu is a hypothesis, not confirmed).",
    "- Why 1523 and 1526 together account for nearly a quarter of the records.",
    "",
    "See `docs/data_provenance.md` for the eligibility checklist that must be completed by the author.",
]

OUT_MD.parent.mkdir(parents=True, exist_ok=True)
OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT_MD}")
print("\n".join(lines[:20]))
